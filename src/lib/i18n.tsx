type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: Dict };
const I18nCtx = createContext<Ctx | null>(null);

export function I18nProvider({
  children,
  initialLang,
}: {
  children: ReactNode;
  initialLang?: Lang;
}) {
  const [lang, setLangState] = useState<Lang>(initialLang ?? "ru");
  useEffect(() => {
    if (initialLang) {
      setLangState(initialLang);
      return;
    }
    try {
      const saved = localStorage.getItem("lang") as Lang | null;
      if (saved === "ru" || saved === "en") setLangState(saved);
    } catch {
      // localStorage can be unavailable during SSR or in hardened browsers.
    }
  }, [initialLang]);
  const setLang = (l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem("lang", l);
    } catch {
      // Persisting language is optional; UI state has already been updated.
    }
  };
  return <I18nCtx.Provider value={{ lang, setLang, t: dict[lang] }}>{children}</I18nCtx.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nCtx);
  if (!ctx) throw new Error("I18nProvider missing");
  return ctx;
}
